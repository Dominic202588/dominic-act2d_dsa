    private void btn_calculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_calculateActionPerformed
        // TODO add your handling code here:
        int quantity;
        double piatos = 0;
        double nova = 0;
        double snackstot = 0;
        double coke = 0;
        double mountainDew = 0;
        double drinkstot = 0;
        double price = 0;
        double subtotal = 0;
        
        
        try{
        quantity = Integer.parseInt(txt_quantity.getText());
        }catch(NumberFormatException e){
        JOptionPane.showMessageDialog(this, "Please enter a valid quantity.", "Invalid quantity", JOptionPane.WARNING_MESSAGE);
        return;
        }

        //Check quantity
        if(quantity <= 0){
            JOptionPane.showMessageDialog(this, "Quantity must be greater than 0.", "Invalid Quantity", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        
        
        //Check selected item
        if(rdb_piatos.isSelected()){
            piatos = 22;
        }
        if(rdb_nova.isSelected()){
            nova = 25;
        }
        
        snackstot = piatos + nova;
        
        //Check selected item
        if(rdb_coke.isSelected()){
            coke = 22;
        }
        if(rdb_mountainDew.isSelected()){
            mountainDew = 25;
        }
        
        //Calculate snacks and drinks
        drinkstot = coke + mountainDew;
        
        price = snackstot + drinkstot;
                
        //Calculate Subtotal
        subtotal = quantity * price;
        
        //Display Price
        txt_price.setText(String.format("₱%.2f",price));
        
        //Display Subtotal
        txt_subtotal.setText(String.format("₱%.2f",subtotal));
        
        JOptionPane.showMessageDialog(this, "Order details calculated successfully!", "Cafeteria", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btn_calculateActionPerformed

    private void btn_paymentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_paymentActionPerformed
        // TODO add your handling code here:
        double cash;
        double subtotal;
        double change;
        
        //Check if order details where calculated
        if(txt_subtotal.getText().isEmpty()){
           JOptionPane.showMessageDialog(this, "Please calculate the order detail first.", "No Oerder", JOptionPane.WARNING_MESSAGE);
           return;
        }
        
        //Get Cash
        try{
            cash = Double.parseDouble(txt_cash.getText());
        }catch(NumberFormatException e){
        JOptionPane.showMessageDialog(this, "Please enter a valid cash.", "Invalid Cash", JOptionPane.WARNING_MESSAGE);
        return;
        }
        
        //Get Subtotal
        try{
            String subtotalText = txt_subtotal.getText().replace("₱","").trim();
            subtotal = Double.parseDouble(subtotalText);
        }catch(NumberFormatException e){
        JOptionPane.showMessageDialog(this, "Invalid subtotal.", "Error", JOptionPane.WARNING_MESSAGE);
        return;
        }
        
        //Check Cash 
        if(cash < subtotal){
            JOptionPane.showMessageDialog(this, "Insufficient cash!.", "Payment Error", JOptionPane.WARNING_MESSAGE);
            txt_change.setText("₱0.00");
            return;
        }
        
        
        
        //Calculate Change
        change = cash - subtotal;
        
        //Display Change 
        txt_change.setText(String.format("₱%.2f",change));
        
        //Payment Success
        JOptionPane.showMessageDialog(this, "Payment successful!\n\n" + "Subtotal:₱"+String.format("₱%.2f",subtotal) + "\nCash:₱"+String.format("₱%.2f",cash)+"\nChange:₱"+String.format("₱%.2f",change), "Payment Complete", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btn_paymentActionPerformed

