    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String p1 = txt_p1.getText().trim().toUpperCase();
        String p2 = txt_p2.getText().trim().toUpperCase();
        
        //Rock
        if(p1.equals("ROCK") && p2.equals("ROCK")){
           JOptionPane.showMessageDialog(rootPane, "DRAW", "RPS", JOptionPane.INFORMATION_MESSAGE);
        } 
        else if(p1.equals("ROCK") && p2.equals("PAPER")){
           JOptionPane.showMessageDialog(rootPane, "Player 2 Win!", "RPS", JOptionPane.INFORMATION_MESSAGE);
        }
        else if(p1.equals("ROCK") && p2.equals("SCISSORS")){
           JOptionPane.showMessageDialog(rootPane, "Player 1 Win!", "RPS", JOptionPane.INFORMATION_MESSAGE);
        }
        
        //PAPER
        else if(p1.equals("PAPER") && p2.equals("ROCK")){
           JOptionPane.showMessageDialog(rootPane, "Player 1 Win!", "RPS", JOptionPane.INFORMATION_MESSAGE);
        } 
        else if(p1.equals("PAPER") && p2.equals("PAPER")){
           JOptionPane.showMessageDialog(rootPane, "DRAW", "RPS", JOptionPane.INFORMATION_MESSAGE);
        }
        else if(p1.equals("PAPER") && p2.equals("SCISSORS")){
           JOptionPane.showMessageDialog(rootPane, "Player 2 Win!", "RPS", JOptionPane.INFORMATION_MESSAGE);
        }
        
        //SCISSORS
        else if(p1.equals("SCISSORS") && p2.equals("ROCK")){
           JOptionPane.showMessageDialog(rootPane, "Player 2 Win!", "RPS", JOptionPane.INFORMATION_MESSAGE);
        } 
        else if(p1.equals("SCISSORS") && p2.equals("PAPER")){
           JOptionPane.showMessageDialog(rootPane, "Player 1 Win!", "RPS", JOptionPane.INFORMATION_MESSAGE);
        }
        else if(p1.equals("SCISSORS") && p2.equals("SCISSORS")){
           JOptionPane.showMessageDialog(rootPane, "DRAW", "RPS", JOptionPane.INFORMATION_MESSAGE);
        }
        else{
           JOptionPane.showMessageDialog(rootPane, "PLEASE CHOOSE AND USE UPPERCASE(ROCK, PAPER, AND SCISSORS)", "RPS", JOptionPane.ERROR_MESSAGE);
        }
        
        
    }//GEN-LAST:event_jButton1ActionPerformed

